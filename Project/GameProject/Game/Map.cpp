void Map::Draw() {
    for (int y = 0; y < MAP_ROWS; y++) {
        for (int x = 0; x < MAP_COLS; x++) {
            if (m_data[y][x] != 0) {
                CVector2D tile_pos(
                    x * MAP_TIP_SIZE + MAP_TIP_SIZE / 2,
                    y * MAP_TIP_SIZE + MAP_TIP_SIZE / 2
                );

                m_img.SetSize(MAP_TIP_SIZE, MAP_TIP_SIZE);
                m_img.SetCenter(MAP_TIP_SIZE / 2, MAP_TIP_SIZE / 2);
                m_img.SetRect(48 * m_data[y][x], 0, 48 * (m_data[y][x] + 1), 48);
                m_img.SetPos(GetScreenPos(tile_pos));
                m_img.Draw();
            }
        }
    }
    //DrawRect();
}

int Map::CollisionRect(const CVector2D& pos, const CRect& rect) const {

    float p_left = pos.x + rect.m_left;
    float p_top = pos.y + rect.m_top;
    float p_right = pos.x + rect.m_right;
    float p_bottom = pos.y + rect.m_bottom;

    int tile_start_x = (int)floor(p_left / MAP_TIP_SIZE);
    int tile_end_x = (int)floor((p_right - 1) / MAP_TIP_SIZE);
    int tile_start_y = (int)floor(p_top / MAP_TIP_SIZE);
    int tile_end_y = (int)floor((p_bottom - 1) / MAP_TIP_SIZE);


    for (int y = tile_start_y; y <= tile_end_y; y++) {
        for (int x = tile_start_x; x <= tile_end_x; x++) {

            if (x < 0 || x >= MAP_COLS || y < 0 || y >= MAP_ROWS) continue;

            if (m_data[y][x] != 0) {
                float t_left = x * MAP_TIP_SIZE;
                float t_top = y * MAP_TIP_SIZE;
                float t_right = (x + 1) * MAP_TIP_SIZE;
                float t_bottom = (y + 1) * MAP_TIP_SIZE;

                if (CheckRectCollision(p_left, p_top, p_right, p_bottom, t_left, t_top, t_right, t_bottom)) {
                    return m_data[y][x];
                }
            }
        }
    }

    return 0;
}


